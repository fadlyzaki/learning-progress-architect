export function translate(
  locale: Locale,
  key: string,
  params: Record<string, string | number> = {},
) {
  const template = messages[locale][key] ?? messages.en[key] ?? key;

  return template.replace(/\{(\w+)\}/g, (_, token: string) => String(params[token] ?? `{${token}}`));
}
